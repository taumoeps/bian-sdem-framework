"""The authoring guide — how an outside author (an AI assistant such as ChatGPT, or a person without the CLI) writes a FULL design as
SDEM data, A1 to A4 (docs/design/sdem-authoring-guide-design.md AU-01…AU-06). One Markdown file to hand over: the method, the files to
produce, the rules, what SDEM will check, the hand-over checklist — and SDEM's vocabulary, generated from the metamodel so it is always
this version's. Printed by `sdem types authoring`; kept as docs/reference/authoring-guide.md (`sdem model check` fails when it is stale).

  python -m sdem.authorguide            # write docs/reference/authoring-guide.md
  python -m sdem.authorguide --check    # is it current?
"""
import argparse, json

from .paths import DATA_ROOT as ROOT, version

OUT = ROOT / 'docs' / 'reference' / 'authoring-guide.md'

INTRO = '''# Authoring a full design as SDEM data — A1 to A4

> **For an AI assistant or any author who does not run SDEM.** Generated by SDEM {version} (metamodel {mm}) — `sdem types authoring`. Hand this one file to the author with the design. It is complete on its own.

SDEM holds a solution design as records in four layers — **A1** business, **A2** BIAN service domains, **A3** application, **A4** technology — with links inside each layer and links between layers. You write the records and the links inside A1, A3 and A4. SDEM takes A2 from BIAN itself, proposes the links between layers, and a person approves them. Then SDEM checks the design, completes a first draft by its own rules, and an architect refines it.

**Your work is judged by three things:** SDEM accepts every record and link you wrote (the vocabulary below is exact); nothing in your files is something the design does not say; and where the design is silent, you said so.

## 1. What you hand over — eight files

| File | What it holds |
|---|---|
| `a1-business.json` | the business layer: `{{"level": "A1", "instances": [records], "relationships": [links]}}` |
| `a3-application.json` | the application layer, same form, `"level": "A3"` |
| `a4-technology.json` | the technology layer, same form, `"level": "A4"` |
| `BIAN-DOMAINS.json` | `{{"release": "…", "service_domains": [{{"name": BIAN's exact name, "source": design section}}], "operations": [{{"service_domain", "name", "used_by": [A1 process ids], "source"}}], "bank_local_not_bian": [names the design uses that are NOT BIAN service domains]}}` |
| `CROSS-LAYER-SUGGESTIONS.json` | `{{"status": "UNAPPROVED", "suggestions": [{{"source": id, "link_type": one of section 6's, "target": id, "design_section", "basis": "stated" or "implied", "reason"}}]}}` |
| `NOT-STATED.json` | `{{"items": [{{"record_id", "detail": what the design does not say, "design_section"}}]}}` — every place rule 10 could not be met, every value left out |
| `CHECKLIST.json` | the result of each check in section 7, with counts — and `"cli_executed": false` |
| `README.md` | what you did, from which design, and its limits |

## 2. The method — in this order

1. **Read the whole design first.** Number its sections; every record and link you write cites one.
2. **List the records, layer by layer, top down** — a full design has, where the design speaks of them:
   - **A1**: actors and roles; capabilities; the value stream and its stages; processes and their steps (activities); events; the information handled (business objects); services; products; channels (business interfaces); and every requirement as its own record.
   - **A2**: nothing written — the BIAN service domains the design names go in `BIAN-DOMAINS.json`.
   - **A3**: application components; the services each offers; interfaces; API operations with method and path; functions; events; data entities **with every column as a data attribute**.
   - **A4**: nodes and devices; system software (databases, queues, key stores, monitoring); technology services; deployments (one per component and environment); environments; network zones; locations; artifacts; paths between nodes.
3. **Use the design's own names** for records, exactly. Give each a short stable id of your own (`APP-LEDGER`), used consistently in every file.
4. **Write the links inside each layer** — only the combinations section 5 lists, in that direction.
5. **Meet rule 10 for every record** — or list it in `NOT-STATED.json`. Do both passes: every record has the links its kind needs; every link has two records that exist.
6. **List the links between layers** as suggestions, each with the design section that supports it.
7. **Run the checklist** (section 7) on your own files and report it honestly.

## 3. The rules

1. One file per layer; **never write the A2 file** and never invent a service domain. A bank-local concept ("consent control") is not BIAN: list it under `bank_local_not_bian`.
2. A record: `{{"id", "type", "version": "1", "name", "lifecycle_status", "description" (optional), "attributes": {{…}}}}`. `lifecycle_status`: planned, active, deprecated or retired.
3. **Where the design does not state a value, leave the attribute out, mark the record `planned`, and list it in `NOT-STATED.json`.** Never a placeholder (`TBD`, `unknown`, `3.x`, `n/a`): SDEM reads it as wrong. A `planned` record may omit required attributes; an `active` one may not.
4. An attribute with allowed values takes exactly one of them, spelled as shown.
5. A link inside a layer: `{{"source": id, "kind": kind, "target": id}}` — the (source type, kind, target type) must be listed in section 5. A subtype may use its parent's links. If the link you want is not listed, it is not allowed: use the one that is, or leave it out and say so.
6. **Links between layers are never written in a layer file** — only suggested.
7. Cite the design on every record and link: `"source_id": "document:design.md#4"` (in `attributes` for a record).
8. Network zones: `zone_level` 0 with `zone_kind` on_premises or cloud; level 1 internal or dmz; level 2 private. A "restricted" zone is *private*, level 2. A design that simply lists its zones has no level-0 zone — do not add one.
9. **Do not invent to complete.** No image names, host names, providers, versions, owners or links the design does not give. SDEM completes the draft by its own rules, marked as inferred; an invented fact in your files cannot be told from a stated one.
10. **Every record is connected** — section 4 lists what SDEM checks. Meet it from what the design says, or list the record in `NOT-STATED.json`.

'''

CHECKS = '''## 7. Before you hand over — run each check on your own files

| Check | Passes when |
|---|---|
| Types | every `type` is in section 5 and not abstract |
| Attributes | every attribute name is listed for the type or its parent; every value with allowed values is one of them; no placeholder anywhere |
| Links | every link is a (source type, kind, target type) section 5 lists, in that direction; both ids exist in the same file |
| No A2, no cross-layer | no `a2-…` file; no link between layers inside a layer file; every suggestion's link type and end types are in section 6 |
| Connected | every record meets section 4, or is in `NOT-STATED.json` with what the design does not say |
| Traceable | every record and link cites a design section that says it; nothing in the files is absent from the design |
| Honest | `CHECKLIST.json` says `"cli_executed": false`; nothing is described as validated by SDEM |

A design with nothing in `NOT-STATED.json` is almost always one where something was invented. Loose ends, named, are the mark of a faithful conversion.
'''


def _standards():
    """What SDEM will check, from the standards and patterns it ships — so the guide and the check never drift."""
    L = ['## 4. What SDEM will check — a complete design', '',
         "SDEM's own standard for a complete design (it never fails a design; each unmet rule is a gap the architect sees). *Between layers* means a link you suggest and a person approves.", '',
         '| Rule | Applies to | A complete design has |', '|---|---|---|']
    std = json.loads((ROOT / 'standards' / 'sdem-completeness.json').read_text(encoding='utf-8'))
    def say(r):
        if r.get('link'): l = r['link']; return f"`{l['kind']}` {'from' if l.get('direction') == 'in' else 'to'} {l.get('to', 'another record')}"
        if r.get('any_link'): return ' **or** '.join((f"*between layers* `{l['relationship']}`" if l.get('relationship') else f"`{l['kind']}` {'from' if l.get('direction') == 'in' else 'to'} {l.get('to', 'another record')}") for l in r['any_link'])
        if r.get('across'): return f"*between layers* `{r['across']['relationship']}`"
        return ''
    for r in std['rules']: L.append(f"| {r['id']} | {r['entity']} | {r['message']} — {say(r)} |")
    pats = []
    for f in sorted((ROOT / 'standards').glob('*.json')):
        d = json.loads(f.read_text(encoding='utf-8'))
        if d.get('format') == 'sdem-pattern/1': pats.append(d)
    if pats:
        L += ['', '**Patterns for kinds of solution.** Where the design is one of these, SDEM also looks for these parts. Write each part the design has; list each it lacks in `NOT-STATED.json` — do not add a part to satisfy a pattern.', '']
        for d in pats:
            p, S = d['pattern'], d['structure']; aw = p['applies_when']
            when = ', '.join(f'{k} = {v}' for k, v in (aw.get('when') or {}).items())
            L += [f"- **{p['title']}** — applies to a design with {aw['entity'].split('.')[1]} where {when}: " +
                  '; '.join((r.get('label') or r['id']) + (f" (at least {r['min']})" if r.get('min', 1) > 1 else '') for r in S['roles'] if r['id'] != S['anchor']) + '.']
    return L + ['']


def _vocabulary(mm):
    from .typeinfo import describe_type
    from .layers import layers
    L = ['## 5. The vocabulary — every kind of record, its attributes and its links inside the layer', '',
         'Only what is listed here is accepted. *Links from it*: kind → the types it may point to. *Links to it*: kind ← the types that may point to it.', '']
    cross = {}
    for layer in layers():
        code = layer['code']
        if code not in ('A1', 'A3', 'A4'): continue
        L += [f"### {layer['name']} — `{layer['file']}`", '']
        for t, e in sorted(mm.entities.items()):
            if e['level'] != code or e.get('artefact'): continue
            d = describe_type(mm, t, full=False)
            L += [f"#### {t}" + (' *(abstract — never a record; use a subtype)*' if d['abstract'] else ''), '',
                  f"{d['definition']} — {d['source']}." + (f" A kind of {', '.join(d['extends'])}." if d['extends'] else ''), '']
            at = [a for a in d['attributes'] if a['name'] != 'inferred']
            if at:
                L += ['| Attribute | Type | Required | Allowed values / refers to | Meaning |', '|---|---|---|---|---|']
                for a in at:
                    vals = ', '.join(f'`{v}`' for v in a.get('allowed_values') or a.get('values') or []) or (('→ ' + ', '.join(a['refers_to'])) if a.get('refers_to') else '')
                    L.append(f"| `{a['name']}` | {a.get('type', '')} | {'yes' if a.get('required') else ''} | {vals} | {(a.get('description') or '').replace('|', '/')} |")
                L.append('')
            out, inn = {}, {}
            for l in d['links_out']: out.setdefault(l['kind'], set()).add(l['to'].split('.')[1])
            for l in d['links_in']: inn.setdefault(l['kind'], set()).add(l['from'].split('.')[1])
            if out: L += ['**Links from it:** ' + '; '.join(f"`{k}` → {', '.join(sorted(v))}" for k, v in sorted(out.items())) + '.', '']
            if inn: L += ['**Links to it:** ' + '; '.join(f"`{k}` ← {', '.join(sorted(v))}" for k, v in sorted(inn.items())) + '.', '']
            if not out and not inn: L += ['No links inside the layer.', '']
            for x in d['link_types_to_other_layers']:
                key = (t, x['relationship'], x['other_end']) if x['direction'] == 'out' else (x['other_end'], x['relationship'], t)
                cross[key] = x['evidence_needed']
    L += ['## 6. Links between layers — suggested, never written', '', '| From | Link type | To | Evidence a person gives to approve it |', '|---|---|---|---|']
    for (s, r, t), ev in sorted(cross.items(), key=lambda k: (k[0][1], k[0][0], k[0][2])): L.append(f"| {s} | `{r}` | {t} | {', '.join(ev)} |")
    return L + ['']


def render():
    from . import profile as _p
    from .metamodel import Metamodel
    _p.deactivate()   # SDEM's own vocabulary: an organisation's profile is not part of what an outside author is given
    mm = Metamodel.load()
    return INTRO.format(version=version(), mm=mm.version) + '\n'.join(_standards() + _vocabulary(mm)) + '\n' + CHECKS


def main(argv=None):
    ap = argparse.ArgumentParser(prog='sdem-authorguide'); ap.add_argument('--check', action='store_true'); a = ap.parse_args(argv)
    t = render()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding='utf-8') == t
        print(f"{OUT.name}: {'up to date' if ok else 'STALE: regenerate with sdem model regenerate'}"); return 0 if ok else 1
    OUT.write_text(t, encoding='utf-8'); print(f'wrote {OUT.relative_to(ROOT)}'); return 0


if __name__ == '__main__':
    raise SystemExit(main())
