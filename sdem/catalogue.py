"""Render docs/entity-catalogue.md — every architecture and entity type, with source reference, reasoning and confidence.

Generated from the entity catalogue (metamodel/a1…a4-*.json); the test suite checks it is current.
"""
from pathlib import Path
from collections import Counter
import argparse, json
from sdem.metamodel import Metamodel, MM_DIR, LEVEL_FILES
from sdem.terms import apply as _terms

DOC = MM_DIR.parent / 'docs' / 'entity-catalogue.md'
NAMES = {'A1': 'A1 Business Architecture', 'A2': 'A2 Service Domain Architecture', 'A3': 'A3 Application Architecture', 'A4': 'A4 Technology Architecture'}
SOURCE = {'bian_reference': 'BIAN reference', 'bian_aligned': 'aligned to BIAN', 'archimate_native': 'ArchiMate native', 'archimate_aligned': 'aligned to ArchiMate',
          'togaf_informed': 'TOGAF-informed', 'sdem_extension': 'SDEM extension', 'sdmm_extension': 'SDEM extension', 'bank_extension': 'institution extension'}
STATUS = {'confirmed_in_official_source': 'concept confirmed', 'pending_release_validation': 'pending BIAN release validation',
          'interpreted_from_official_source': 'interpreted from source', 'proposed_extension': 'SDEM proposal'}


def render():
    ents = [e for f in LEVEL_FILES for e in json.loads((MM_DIR / f).read_text(encoding='utf-8'))['entities']]
    conf = Counter(e['confidence'] for e in ents); src = Counter(SOURCE[e['definition_source']] for e in ents)
    out = ['# SDEM entity catalogue — sources, reasoning and confidence', '',
           'Generated by `python -m sdem.catalogue` from `metamodel/a1…a4-*.json`; the test suite checks it is current. One row per entity type of the Architecture Metamodel.', '',
           '**Confidence** is the strength of the source basis: **high** — the concept exists one-to-one in a public standard; **medium** — interpreted from, or an SDEM extension of, a standard concept; **low** — SDEM design with no standard concept. **Verification** is what has been checked: BIAN concepts against the public portal (a licensed release is still pending); ArchiMate concepts against the open-source Archi implementation of the relationship tables, since the specification text is login-gated.', '',
           '## Summary', '', '| | Count |', '|---|---|', f"| Entity types | {len(ents)} |"]
    out += [f"| Confidence {k} | {conf[k]} |" for k in ('high', 'medium', 'low')]
    out += [f"| Source: {k} | {v} |" for k, v in src.most_common()]
    out.append('')
    for lvl in ('A1', 'A2', 'A3', 'A4'):
        rows = [e for e in ents if e['level'] == lvl]
        out += [f"## {NAMES[lvl]}", '', '| Entity | Kind | Source reference | Source type | Verification | Reasoning | Confidence |', '|---|---|---|---|---|---|---|']
        for e in rows:
            r = e['reference']; kind = 'abstract' if e['abstract'] else 'artefact' if e['artefact'] else 'concrete'
            if e.get('extends'): kind += f", extends `{e['extends']}`"
            ref = f"{r['standard']} {r['release']}: *{r['concept']}*" + (f", {r['locator']}" if r.get('locator') else '') + f" ([link]({r['uri']}))"
            out.append(f"| `{e['type']}` | {kind} | {ref} | {SOURCE[e['definition_source']]} ({e['alignment_kind']}) | {STATUS.get(e['evidence_status'], e['evidence_status'])} | {e['reasoning']} | **{e['confidence']}** |")
        out.append('')
    return _terms('\n'.join(out) + '\n')


def main(argv=None):
    parser = argparse.ArgumentParser(prog='sdem-catalogue', description='Render docs/entity-catalogue.md from the entity catalogue.')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        ok = DOC.exists() and DOC.read_text(encoding='utf-8') == text
        print('up to date' if ok else 'STALE: regenerate with python -m sdem.catalogue'); return 0 if ok else 1
    DOC.write_text(text, encoding='utf-8'); print(f'wrote {DOC}'); return 0


if __name__ == '__main__':
    raise SystemExit(main())
