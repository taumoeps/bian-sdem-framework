"""Render docs/architecture-attribute-design.md — the SDEM Architecture Attribute Design: the fields every instance carries
and each entity type's own attributes, with source reference, verification, reasoning and confidence.

Generated from metamodel/entity-attributes.json; the test suite checks it is current.
"""
from pathlib import Path
from collections import Counter
import argparse, json
from sdem.metamodel import MM_DIR
from sdem.terms import apply as _terms

REC = MM_DIR / 'entity-attributes.json'
DOC = MM_DIR.parent / 'docs' / 'architecture-attribute-design.md'
NAMES = {'A1': 'A1 Business Architecture', 'A2': 'A2 Service Domain Architecture', 'A3': 'A3 Application Architecture', 'A4': 'A4 Technology Architecture'}


def load(path=REC):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def render(rec=None):
    rec = rec or load(); A = rec['attributes']
    act = [a for a in A if a['status'] == 'active']
    conf = Counter(a['confidence'] for a in act); src = Counter(a['source'] for a in act)
    out = ['# SDEM Architecture Attribute Design', '',
           'Generated by `python -m sdem.attributes` from `metamodel/entity-attributes.json`; the test suite checks it is current. Part of the **Architecture Metamodel**, beside [`architecture-entity-design.md`](architecture-entity-design.md) (which entity types exist) and [`relationships-planning.md`](relationships-planning.md) (which links are allowed): this document defines **which fields each entity type carries**, where each field comes from, why, and how confident that basis is.', '',
           '## 1. Design principles', '',
           '1. **A standard\'s field is used as the standard defines it.** BIAN defines the A2 fields and OpenAPI the API fields; SDEM names the section.',
           '2. **ArchiMate defines no attributes.** Its elements have a name, documentation and free-form properties only. So every A1, A3 and A4 field is either a **relationship SDEM records on the entity** (so a rule can join on it) or a **field SDEM defines**; each says which.',
           '3. **Institution data is data.** Aliases — the bank\'s own names for assets, qualifiers, fields and glossary terms — are supplied in the export, never inferred (the H2 finding: recall 0.78 → 1.00 when they were supplied).',
           '4. **Every field is read by something or says so.** Each attribute names the rules or steps that read it; informational fields are marked as such.',
           '5. **Redundant fields are deprecated, not deleted.** A field that duplicates a within-level relationship is kept readable and marked deprecated.', '',
           '## 2. How each attribute is recorded', '',
           '| Field | Meaning |', '|---|---|',
           '| ID | `AT-<level>-<n>`, stable |', '| Type | `string`, `list<string>`, `map<string,string>`, or an enum |',
           '| Required | **yes** where a rule depends on it and every example estate supplies it; otherwise optional. **Not yet enforced** by `sdem-graph check` — enforcement is the next build |',
           '| Source / reference | the standard and section the field comes from, or SDEM / institution |',
           '| Read by | the rules (`S…`) and procedure steps that read the field |',
           '| Verification | what has been checked |',
           f"| **Confidence** | {rec['confidence_rule']} |", '',
           '## 3. Summary', '', '| Architecture | Attributes | High | Medium | Low | Required |', '|---|---|---|---|---|---|']
    for l in ('A1', 'A2', 'A3', 'A4'):
        r = [a for a in act if a['entity'].startswith(l)]; c = Counter(a['confidence'] for a in r)
        out.append(f"| {NAMES[l]} | {len(r)} | {c['high']} | {c['medium']} | {c['low']} | {sum(a['required'] for a in r)} |")
    out += [f"| **All** | **{len(act)}** | **{conf['high']}** | **{conf['medium']}** | **{conf['low']}** | **{sum(a['required'] for a in act)}** |", '',
            f"Plus {len(A) - len(act)} deprecated attribute(s) and {len(rec['core_fields'])} core fields every instance carries.", '',
            '| Source | Attributes |', '|---|---|'] + [f"| {k} | {v} |" for k, v in src.most_common()] + ['']
    out += ['## 4. Core fields (every entity type)', '', 'From `schema/level-model.schema.json`. These are the instance\'s identity and lifecycle, not entity-specific attributes.', '',
            '| Field | Type | Required | Source reference | Description | Reasoning | Confidence |', '|---|---|---|---|---|---|---|']
    out += [f"| `{c['name']}` | {c['type']} | {'yes' if c['required'] else 'no'} | {c['source']}: {c['reference']['standard']}, {c['reference']['locator']} ([link]({c['reference']['uri']})) | {c['description']} | {c['reasoning']} | **{c['confidence']}** |" for c in rec['core_fields']]
    out.append('')
    n = 4
    for l in ('A1', 'A2', 'A3', 'A4'):
        n += 1
        out += [f"## {n}. {NAMES[l]}", '', '| ID | Entity | Attribute | Type | Required | Source reference | Read by | Verification | Reasoning | Confidence |', '|---|---|---|---|---|---|---|---|---|---|']
        for a in [a for a in A if a['entity'].startswith(l)]:
            r = a['reference']; ref = f"{a['source']}: {r['standard']}" + (f", {r['locator']}" if r['locator'] not in ('—', '') else '') + f" ([link]({r['uri']}))"
            name = f"`{a['name']}`" + (' *(deprecated)*' if a['status'] == 'deprecated' else '')
            out.append(f"| {a['id']} | `{a['entity']}` | {name} | {a['type']} | {'yes' if a['required'] else 'no'} | {ref} | {a['read_by']} | {a['verification']} | {a['reasoning']} | **{a['confidence']}** |")
        out.append('')
    low = [a for a in A if a['confidence'] == 'low']
    sdem = [a for a in act if a['source'] == 'SDEM']
    out += [f'## {n + 1}. Fields SDEM defines', '', f'{len(sdem)} active attributes have SDEM as their source: no standard defines the field. They are where inference concentrates and what a reviewer should challenge first; the {len(low)} rated **low** have no standard concept behind them at all.', '',
            '| ID | Attribute | Confidence | Read by |', '|---|---|---|---|'] + [f"| {a['id']} | `{a['entity']}.{a['name']}` | {a['confidence']} | {a['read_by']} |" for a in sdem] + ['']
    out += [f'## {n + 2}. Review points', '',
            '- **`A3.APIOperation.payload_fields` is medium, not high**: OpenAPI describes payloads as schemas; SDEM flattens them to field names, which loses structure (nested objects, arrays).',
            '- **`A2.ControlRecord.lifecycle_states` is SDEM\'s**: BIAN describes a control record as tracking an asset through its lifecycle but publishes no state list.',
            '- **`A1.BusinessService.inputs` / `outputs` are low**: no standard gives a business service inputs and outputs; SDEM added them for rule S09.',
            '- **`A3.ApplicationComponent.accesses` is deprecated**: it duplicates the A3 `access` relationship; exports should use the relationship.',
            '- **`A3.Event.published_to`** would gain a public source if AsyncAPI were adopted (a channel).',
            '- **Required flags reflect today\'s examples.** Turning them into checks is the next build; a real export may show that a "required" field is often missing, which is a finding, not a failure of the export.', '',
            '## Related', '', '- [`architecture-entity-design.md`](architecture-entity-design.md) — the entity types.', '- [`inference-audit.md`](inference-audit.md) — how much of SDEM is grounded, confirmed or inferred.',
            '- `metamodel/export-conventions.json` — the join keys each rule reads; every key there appears here.', '']
    return _terms('\n'.join(out) + '\n')


def main(argv=None):
    parser = argparse.ArgumentParser(prog='sdem-attributes', description='Render docs/architecture-attribute-design.md from metamodel/entity-attributes.json.')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        ok = DOC.exists() and DOC.read_text(encoding='utf-8') == text
        print('up to date' if ok else 'STALE: regenerate with python -m sdem.attributes'); return 0 if ok else 1
    DOC.write_text(text, encoding='utf-8'); print(f'wrote {DOC}'); return 0


if __name__ == '__main__':
    raise SystemExit(main())
